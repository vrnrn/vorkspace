//! Named Bot workspaces expose the existing file owner without copying memory.
use super::{files, Bot};
use crate::{accounts::Profile, kind::Kind, session::Session};
use std::{
    io::Write,
    os::unix::fs::OpenOptionsExt,
    path::{Path, PathBuf},
};

const SESSION_MARKER: &str = "<!-- Generated by vorkspace: Bot session -->\n";

fn homes_root(root: &Path) -> Result<PathBuf, String> {
    let data = root.parent().ok_or("Bot storage has no parent directory")?;
    let desktop = crate::compatibility::vorkspace_database();
    if desktop.parent().is_some_and(|path| same_path(data, path)) {
        return crate::shell_env::home()
            .map(|home| home.join(".vorkspace/bots"))
            .ok_or_else(|| "Could not find your home directory".into());
    }
    // Development profiles and fixtures must never publish into the user's
    // desktop Bot namespace, even when they contain copies of the same IDs.
    Ok(data.join("bot-workspaces"))
}

fn same_path(a: &Path, b: &Path) -> bool {
    a == b
        || a.canonicalize()
            .ok()
            .zip(b.canonicalize().ok())
            .is_some_and(|(a, b)| a == b)
}

fn folder_name(label: &str) -> String {
    let name: String = label
        .trim()
        .chars()
        .take(48)
        .map(|c| {
            if c.is_control() || matches!(c, '/' | '\\' | ':') {
                '-'
            } else {
                c
            }
        })
        .collect();
    let name = name.trim_matches(|c: char| c == '.' || c.is_whitespace());
    if name.is_empty() {
        "Bot".into()
    } else {
        name.into()
    }
}

fn owned_alias(path: &Path, owner: &Path) -> bool {
    path.symlink_metadata()
        .is_ok_and(|m| m.file_type().is_symlink())
        && same_path(path, owner)
}

/// Retain a saved home across display-name changes. Names are presentation;
/// the directory's target remains the Bot's durable ID-based file owner.
pub fn ensure(root: &Path, bot: &Bot, current: Option<&Path>) -> Result<PathBuf, String> {
    let context = super::load_files(root, bot)?;
    let owner = if bot.storage_id() == bot.id {
        PathBuf::from(&context.dir)
    } else {
        // A Minion has its own session directory but reads its parent's memory.
        PathBuf::from(files::load(root, &bot.id, None)?.dir)
    };
    let owner = owner.canonicalize().map_err(|e| e.to_string())?;
    let homes = homes_root(root)?;
    std::fs::create_dir_all(&homes).map_err(|e| format!("Could not create Bot homes: {e}"))?;
    let path = if let Some(path) = current.filter(|path| {
        path.parent()
            .is_some_and(|parent| same_path(parent, &homes))
            && owned_alias(path, &owner)
    }) {
        path.to_owned()
    } else {
        let name = folder_name(&bot.label());
        let mut selected = None;
        for name in [name.clone(), format!("{name} - {}", bot.id)] {
            let candidate = homes.join(name);
            match std::os::unix::fs::symlink(&owner, &candidate) {
                Ok(()) => {
                    selected = Some(candidate);
                    break;
                }
                Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                    if owned_alias(&candidate, &owner) {
                        selected = Some(candidate);
                        break;
                    }
                }
                Err(e) => return Err(format!("Could not publish Bot home: {e}")),
            }
        }
        selected.ok_or("A different folder already occupies this Bot's home")?
    };
    let instructions = format!(
        "# Bot workspace\n\nThis is the persistent workspace for {}.\n\nRead the standing instructions in `{}/SOUL.md` and the root memory in `{}/MEMORY.md`. Topic memories are in `{}/memory/`. Keep user instructions ahead of saved memory, and verify current project and task state before acting. Change the soul only when the user asks. Keep memory concise; never save credentials.\n\nVorkspace supplies authenticated app controls during managed turns. Outside the app, those controls may be unavailable; do not reuse stale endpoint credentials from conversation history. See `SESSION.md` for assigned projects, the provider session and the resume command.\n",
        bot.label(), context.dir, context.dir, context.dir
    );
    // Once created, AGENTS.md belongs to the user. Do not replace their edits.
    match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(owner.join("AGENTS.md"))
    {
        Ok(mut file) => {
            file.write_all(instructions.as_bytes())
                .and_then(|()| file.sync_all())
                .map_err(|e| e.to_string())?;
        }
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {}
        Err(e) => return Err(format!("Could not write Bot instructions: {e}")),
    }
    Ok(path)
}

fn quote(text: &str) -> Result<String, String> {
    shlex::try_quote(text)
        .map(|value| value.into_owned())
        .map_err(|e| e.to_string())
}

/// A readable pointer to provider-owned history, never a copied transcript.
pub fn write_session(
    root: &Path,
    bot: &Bot,
    session: &Session,
    account: &Profile,
) -> Result<(), String> {
    publish_session(root, bot, session, account, true)
}

/// Refresh only the home currently pointing at this app session. Callers hold
/// the Store lock through publication, serializing this with a session reset.
pub fn refresh_session(
    root: &Path,
    bot: &Bot,
    session: &Session,
    account: &Profile,
) -> Result<(), String> {
    publish_session(root, bot, session, account, false)
}

fn publish_session(
    root: &Path,
    bot: &Bot,
    session: &Session,
    account: &Profile,
    replace_session: bool,
) -> Result<(), String> {
    let files = files::load(root, &bot.id, None)?;
    let path = Path::new(&files.dir).join("SESSION.md");
    let previous = match std::fs::read_to_string(&path) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.to_string()),
    };
    let marker = format!("{SESSION_MARKER}<!-- App session: {} -->\n", session.id);
    if previous
        .as_ref()
        .is_some_and(|text| !text.starts_with(SESSION_MARKER))
        || (!replace_session
            && previous
                .as_ref()
                .is_none_or(|text| !text.starts_with(&marker)))
    {
        return Ok(());
    }
    let kind = Kind::from_id(&session.provider);
    let mut account = account.clone();
    if account.root.is_none() && account.id != crate::accounts::DEFAULT {
        account.root = root.parent().map(Path::to_path_buf);
    }
    let directories = bot
        .projects
        .iter()
        .filter(|project| Path::new(project).is_absolute())
        .map(|project| quote(project).map(|path| format!(" --add-dir {path}")))
        .collect::<Result<Vec<_>, _>>()?
        .concat();
    let resume = if let Some(id) = &session.provider_id {
        match kind {
            Kind::Codex => {
                let private_home = super::codex_home(root, &account.id)?;
                let home = private_home
                    .clone()
                    .map(Ok)
                    .unwrap_or_else(|| account.home(kind))?;
                let mut environment = format!("CODEX_HOME={}", quote(&home.to_string_lossy())?);
                if account.id != crate::accounts::DEFAULT {
                    environment = format!("env -u OPENAI_API_KEY -u CODEX_API_KEY -u CODEX_ACCESS_TOKEN {environment}");
                }
                let config = if private_home.is_some() {
                    environment.push_str(&format!(
                        " CODEX_SQLITE_HOME={}",
                        quote(&home.to_string_lossy())?
                    ));
                    format!(
                        " -c {}",
                        quote(&format!(
                            "sqlite_home={}",
                            serde_json::to_string(&home).map_err(|e| e.to_string())?
                        ))?
                    )
                } else {
                    String::new()
                };
                format!(
                    "```sh\ncd {}\n{environment} codex{config} resume --cd {}{directories} -- {}\n```",
                    quote(&session.cwd)?,
                    quote(&session.cwd)?,
                    quote(id)?
                )
            }
            Kind::Claude => {
                let home = quote(&account.home(kind)?.to_string_lossy())?;
                let environment = if account.id == crate::accounts::DEFAULT {
                    format!("CLAUDE_CONFIG_DIR={home}")
                } else {
                    format!("env -u ANTHROPIC_API_KEY -u ANTHROPIC_AUTH_TOKEN -u CLAUDE_CODE_OAUTH_TOKEN CLAUDE_CONFIG_DIR={home} CLAUDE_SECURESTORAGE_CONFIG_DIR={home}")
                };
                format!(
                    "```sh\ncd {}\n{environment} claude{directories} --resume={}\n```",
                    quote(&session.cwd)?,
                    quote(id)?
                )
            }
            _ => format!("Resume the {} session with ID: {id}", kind.label()),
        }
    } else {
        "Send the Bot a message in Vorkspace to create its provider session.".into()
    };
    let context = super::load_files(root, bot)?;
    let text = format!(
        "{marker}# Bot session\n\nBot: {}\nProvider: {}\nWorking directory: {}\n\n{resume}\n\nThe transcript stays in the provider's native storage; this file points to that same session. Finish the current Bot turn before resuming outside Vorkspace. Completed messages in this Codex or Claude session sync into the same Bot chat on open, while idle, and before the next managed turn. Finish the external turn before sending in Vorkspace. Fresh-session rollover keeps older native sessions in provider history; this file points to the current one.\n\nSoul and memory: `{}` (`SOUL.md`, `MEMORY.md`, `memory/`). The named workspace is an alias to the existing Bot files; no history or memory is copied. Minions read their parent's soul and memory.\n\nAssigned projects:\n{}\n",
        bot.label(), kind.label(), session.cwd, context.dir,
        bot.projects.iter().map(|path| format!("- {path}")).collect::<Vec<_>>().join("\n")
    );
    if previous.as_deref() == Some(&text) {
        return Ok(());
    }
    let temp = path.with_extension(format!("{}.tmp", crate::session::new_id()));
    let result = (|| {
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o600)
            .open(&temp)?;
        file.write_all(text.as_bytes())?;
        file.sync_all()?;
        std::fs::rename(&temp, &path)?;
        std::fs::File::open(path.parent().unwrap())?.sync_all()
    })();
    if let Err(error) = result {
        let _ = std::fs::remove_file(temp);
        return Err(format!("Could not write Bot session pointer: {error}"));
    }
    Ok(())
}


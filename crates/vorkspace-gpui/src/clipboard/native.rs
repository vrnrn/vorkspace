//! Maccy's change-count and confidential-type rules, adapted for RAM-only history.
//! See licenses/LICENSE-MACCY-MIT. No clipboard payload is written to disk.
use super::history::Preview;
use super::history::{Content, MAX_IMAGE_BYTES, MAX_TEXT_BYTES, PREVIEW_SIDE};
use objc2_app_kit::NSPasteboard;
use objc2_foundation::{NSData, NSString};
use std::sync::Arc;

const TEXT: &str = "public.utf8-plain-text";
const IMAGES: [&str; 4] = ["public.png", "public.tiff", "public.jpeg", "public.heic"];
const PRIVATE: [&str; 8] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "com.typeit4me.clipping",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
    "net.antelle.keeweb",
];
#[cfg(not(test))]
pub(super) fn revision() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}
#[cfg(not(test))]
pub(super) fn read(last: &mut isize) -> Option<Content> {
    objc2::rc::autoreleasepool(|_| read_board(&NSPasteboard::generalPasteboard(), last))
}
fn read_board(board: &NSPasteboard, last: &mut isize) -> Option<Content> {
    let revision = board.changeCount();
    if revision == *last {
        return None;
    }
    *last = revision;
    let types = board.types()?;
    if PRIVATE
        .iter()
        .any(|t| types.containsObject(&NSString::from_str(t)))
    {
        return None;
    }
    let kind = IMAGES
        .into_iter()
        .find(|t| types.containsObject(&NSString::from_str(t)))
        .unwrap_or(TEXT);
    let data = board.dataForType(&NSString::from_str(kind))?;
    let max = if kind == TEXT {
        MAX_TEXT_BYTES
    } else {
        MAX_IMAGE_BYTES
    };
    if data.is_empty() || data.len() > max || board.changeCount() != revision {
        return None;
    }
    // Admit length before allocating a retained copy. A changed revision is never
    // combined with the previous revision's type or payload.
    let bytes = data.to_vec();
    if board.changeCount() != revision {
        return None;
    }
    if kind == TEXT {
        Content::text(String::from_utf8(bytes).ok()?)
    } else {
        Some(Content::Image { kind, bytes })
    }
}
#[cfg(not(test))]
pub(super) fn write(content: &Content) -> Option<isize> {
    write_board(&NSPasteboard::generalPasteboard(), content)
}
fn write_board(board: &NSPasteboard, content: &Content) -> Option<isize> {
    let (kind, bytes) = match content {
        Content::Text { value, .. } => (TEXT, value.as_bytes()),
        Content::Image { kind, bytes } => (*kind, bytes.as_slice()),
    };
    board.clearContents();
    board
        .setData_forType(Some(&NSData::with_bytes(bytes)), &NSString::from_str(kind))
        .then(|| board.changeCount())
}

pub(super) fn thumbnail(bytes: &[u8]) -> Option<Arc<Preview>> {
    // Background executor threads are reused; drain native temporary objects
    // per job rather than retaining them until a worker thread exits.
    objc2::rc::autoreleasepool(|_| decode_thumbnail(bytes))
}
fn decode_thumbnail(bytes: &[u8]) -> Option<Arc<Preview>> {
    use objc2_core_foundation::{
        CFBoolean, CFData, CFDictionary, CFNumber, CFType, CGPoint, CGRect, CGSize,
    };
    use objc2_core_graphics::{CGBitmapContextCreate, CGColorSpace, CGContext, CGImage};
    use objc2_image_io::{
        CGImageSource, kCGImageSourceCreateThumbnailFromImageAlways,
        kCGImageSourceCreateThumbnailWithTransform, kCGImageSourceShouldCache,
        kCGImageSourceThumbnailMaxPixelSize,
    };
    // ImageIO decodes a bounded thumbnail directly, including TIFF screenshots,
    // instead of expanding a full-resolution image into the desktop heap.
    let size = CFNumber::new_isize(PREVIEW_SIDE as isize);
    let options = unsafe {
        CFDictionary::<CFType, CFType>::from_slices(
            &[
                kCGImageSourceCreateThumbnailFromImageAlways.as_ref(),
                kCGImageSourceThumbnailMaxPixelSize.as_ref(),
                kCGImageSourceCreateThumbnailWithTransform.as_ref(),
                kCGImageSourceShouldCache.as_ref(),
            ],
            &[
                CFBoolean::new(true).as_ref(),
                size.as_ref(),
                CFBoolean::new(true).as_ref(),
                CFBoolean::new(false).as_ref(),
            ],
        )
    };
    // The source and thumbnail die before this borrowed byte slice. ImageIO
    // therefore needs no second retained copy of the original clipboard image.
    let data = unsafe {
        CFData::with_bytes_no_copy(
            None,
            bytes.as_ptr(),
            bytes.len() as isize,
            objc2_core_foundation::kCFAllocatorNull,
        )
    }?;
    let source = unsafe { CGImageSource::with_data(&data, Some(options.as_opaque())) }?;
    let image = unsafe { source.thumbnail_at_index(0, Some(options.as_opaque())) }?;
    let (w, h) = (CGImage::width(Some(&image)), CGImage::height(Some(&image)));
    if w == 0 || h == 0 || w > PREVIEW_SIDE || h > PREVIEW_SIDE {
        return None;
    }
    let space = CGColorSpace::new_device_rgb()?;
    let mut pixels = vec![0u8; w * h * 4];
    // BGRA, little-endian premultiplied first, matching native CGImage.
    let context = unsafe {
        CGBitmapContextCreate(
            pixels.as_mut_ptr().cast(),
            w,
            h,
            8,
            w * 4,
            Some(&space),
            2 | (2 << 12),
        )
    }?;
    CGContext::draw_image(
        Some(&context),
        CGRect::new(CGPoint::ZERO, CGSize::new(w as f64, h as f64)),
        Some(&image),
    );
    drop(context);
    Some(Arc::new(Preview {
        pixels,
        width: w,
        height: h,
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn native_pasteboard_restores_originals_and_skips_unchanged_private_and_oversized_copies() {
        let board = NSPasteboard::pasteboardWithUniqueName();
        let mut last = board.changeCount();
        let text = Content::text("Clipboard Ω\nsecond line".into()).unwrap();
        write_board(&board, &text).unwrap();
        assert!(read_board(&board, &mut last).as_ref() == Some(&text));
        assert!(read_board(&board, &mut last).is_none());
        for private in PRIVATE {
            write_board(&board, &text).unwrap();
            board.setData_forType(
                Some(&NSData::with_bytes(b"private")),
                &NSString::from_str(private),
            );
            assert!(read_board(&board, &mut last).is_none());
        }
        let image = Content::Image {
            kind: "public.png",
            bytes: vec![1, 2, 3, 4],
        };
        write_board(&board, &image).unwrap();
        assert!(read_board(&board, &mut last).as_ref() == Some(&image));
        let types = board.types().unwrap();
        assert!(!types.containsObject(&NSString::from_str(TEXT)));
        assert!(
            !PRIVATE
                .iter()
                .any(|t| types.containsObject(&NSString::from_str(t)))
        );
        write_board(
            &board,
            &Content::Image {
                kind: "public.png",
                bytes: vec![0; MAX_IMAGE_BYTES + 1],
            },
        )
        .unwrap();
        assert!(read_board(&board, &mut last).is_none());
        board.clearContents();
    }
    #[test]
    fn imageio_previews_are_small_upright_and_support_tiff_screenshots() {
        use image::{DynamicImage, ImageFormat, Rgba, RgbaImage};
        let mut pixels = RgbaImage::from_pixel(1600, 900, Rgba([0, 0, 255, 255]));
        for y in 0..450 {
            for x in 0..1600 {
                pixels.put_pixel(x, y, Rgba([255, 0, 0, 255]));
            }
        }
        let mut png = std::io::Cursor::new(Vec::new());
        DynamicImage::ImageRgba8(pixels)
            .write_to(&mut png, ImageFormat::Png)
            .unwrap();
        let preview = thumbnail(png.get_ref()).unwrap();
        assert!(preview.width <= PREVIEW_SIDE);
        assert!(preview.pixels.len() <= PREVIEW_SIDE * PREVIEW_SIDE * 4);
        // Native pixels are BGRA. The red top and blue bottom retain orientation.
        let pixels = &preview.pixels;
        assert_eq!(&pixels[..4], &[0, 0, 255, 255]);
        assert_eq!(&pixels[pixels.len() - 4..], &[255, 0, 0, 255]);
        use objc2::AnyThread;
        let original = objc2_app_kit::NSImage::initWithData(
            objc2_app_kit::NSImage::alloc(),
            &NSData::with_bytes(png.get_ref()),
        )
        .unwrap();
        let tiff = original.TIFFRepresentation().unwrap();
        assert!(thumbnail(&tiff.to_vec()).is_some());
        let mut transparent = std::io::Cursor::new(Vec::new());
        DynamicImage::ImageRgba8(RgbaImage::from_pixel(32, 16, Rgba([255, 0, 0, 128])))
            .write_to(&mut transparent, ImageFormat::Png)
            .unwrap();
        let preview = thumbnail(transparent.get_ref()).unwrap();
        assert_eq!(&preview.pixels[..4], &[0, 0, 128, 128]);
        assert!(thumbnail(b"broken image").is_none());
    }
}

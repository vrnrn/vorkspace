import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import vm from "node:vm";
import { verifyFormat, verifyPhp, verifySearch } from "./verify.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const asset = path.join(
  root,
  "crates/vorkspace-editor/assets/native-editor.js",
);
const options = {
  absWorkingDir: here,
  entryPoints: ["index.js"],
  outfile: asset,
  bundle: true,
  format: "iife",
  platform: "neutral",
  target: "es2020",
  minify: true,
  nodePaths: [path.join(here, "node_modules")],
  plugins: [
    {
      name: "native-paths",
      setup(build) {
        // Keep all editor extensions on this bundle's package instances.
        build.onResolve(
          { filter: /^@(codemirror|lezer|replit)\// },
          (args) => ({ path: fileURLToPath(import.meta.resolve(args.path)) }),
        );
        build.onLoad(
          { filter: /[/\\]@lezer[/\\]php[/\\]dist[/\\]index\.js$/ },
          async ({ path }) => {
            let contents = await readFile(path, "utf8");
            // Correct token boundaries and heredoc highlighting in
            // @lezer/php 1.0.6. Octal escapes consume at most three 0–7 digits.
            for (const [source, corrected] of [
              [
                "ch >= 48 && ch <= 55 || ch >= 97",
                "ch >= 48 && ch <= 57 || ch >= 97",
              ],
              [
                "input.next >= 48 && input.next <= 55) /* 0-9 */",
                "input.next >= 48 && input.next <= 57) /* 0-9 */",
              ],
              [
                "while (size < 5 && (next = input.peek(size))",
                "while (size < 4 && (next = input.peek(size))",
              ],
              [
                "return size == 2 ? 0 : size + 1",
                "return size == 3 ? 0 : size + 1",
              ],
              [
                "if (match) return input.acceptToken(HeredocString)",
                "if (match && !isIdentifierStart(input.next) && !(input.next >= 48 && input.next <= 57)) return input.acceptToken(HeredocString)",
              ],
              ["String: tags.string,", '"String HeredocString": tags.string,'],
            ]) {
              if (
                !contents.includes(source) ||
                contents.indexOf(source) !== contents.lastIndexOf(source)
              )
                throw new Error(
                  "Revisit PHP digit correction for the installed parser",
                );
              contents = contents.replace(source, corrected);
            }
            return { contents, loader: "js" };
          },
        );
      },
    },
  ],
};
await build(options);
const formatCatalog = [];
const formatPlugins = [];
const formatSources = new Map();
for (const name of [
  "estree",
  "babel",
  "typescript",
  "postcss",
  "html",
  "markdown",
]) {
  const plugin = await import(`prettier/plugins/${name}`);
  formatPlugins.push(plugin);
  const metadata = Object.fromEntries(
    Object.entries(plugin).filter(
      ([key]) => !["default", "parsers", "printers"].includes(key),
    ),
  );
  // Plugin language inference and options remain available before code loads.
  // Reject a dependency update that adds non-data metadata.
  JSON.stringify(metadata, (_key, value) => {
    if (typeof value === "function")
      throw new Error(`Formatter ${name} metadata needs a runtime initializer`);
    return value;
  });
  formatCatalog.push({
    ...metadata,
    name,
    parsers: Object.keys(plugin.parsers ?? {}),
    printers: Object.keys(plugin.printers ?? {}),
  });
  const outfile = asset.replace("native-editor.js", `native-format-${name}.js`);
  await build({
    ...options,
    entryPoints: undefined,
    stdin: {
      contents: `export * from "prettier/plugins/${name}";`,
      resolveDir: here,
    },
    globalName: "vorkspaceFormatPlugin",
    outfile,
  });
  formatSources.set(name, await readFile(outfile, "utf8"));
}
await writeFile(
  asset.replace("native-editor.js", "native-format-plugins.rs"),
  "// Generated by embedded/editor/build.mjs.\n" +
    "const FORMAT_PLUGINS: &[(&str, &str)] = &[\n" +
    formatCatalog
      .map(
        ({ name }) =>
          `    ("${name}", include_str!("native-format-${name}.js")),\n`,
      )
      .join("") +
    "];\n",
);
const formatAsset = asset.replace("native-editor.js", "native-format.js");
await build({
  ...options,
  entryPoints: ["format.js"],
  outfile: formatAsset,
  plugins: [
    ...options.plugins,
    {
      name: "format-catalog",
      setup(build) {
        build.onResolve({ filter: /^native-format-plugins$/ }, () => ({
          path: "native-format-plugins",
          namespace: "format-catalog",
        }));
        build.onLoad({ filter: /.*/, namespace: "format-catalog" }, () => ({
          contents: `export default ${JSON.stringify(formatCatalog)};`,
          loader: "js",
        }));
      },
    },
  ],
});
const searchAsset = asset.replace("native-editor.js", "native-search.js");
await build({
  ...options,
  entryPoints: ["search.js"],
  outfile: searchAsset,
});
// No DOM, Node or external services are available in the native interpreter.
const sandbox = vm.createContext({});
vm.runInContext(await readFile(asset, "utf8"), sandbox);
const sample = JSON.parse(
  await sandbox.vorkspaceAnalyze("test.json", '{"bad": }', "{}"),
);
if (!sample.diagnostics.length || !sample.changes.length)
  throw new Error("Native analysis smoke check failed");
const largeSource = Array.from(
  { length: 300 },
  (_, i) =>
    `export function Component${i}() {\n  return (\n    <div title="example">\n      {true ? <span>hello</span> : null}\n    </div>\n  );\n}\n`,
).join("");
const largeAnalysis = JSON.parse(
  await sandbox.vorkspaceAnalyze(
    "App.tsx",
    largeSource,
    `${largeSource}\nexport const previousHighlightTail = "tail";\n`,
  ),
);
if (!largeAnalysis.tokens.some((token) => token.to > largeSource.length - 1024))
  throw new Error("Large-file highlighting stops before the end of App.tsx");
if (
  !largeAnalysis.changes.some(
    (change) =>
      change.original.includes("previousHighlightTail") &&
      change.tokens.some((token) => token.kind === "var(--syntax-string)"),
  )
)
  throw new Error(
    "Large-file baseline highlighting stops before its final change",
  );
const completion = JSON.parse(
  await sandbox.vorkspaceComplete("test.js", "cons", 4, true),
);
if (!completion.some((option) => option.label === "const"))
  throw new Error("Completion smoke check failed");
const searcher = vm.createContext({});
vm.runInContext(await readFile(searchAsset, "utf8"), searcher);
const search = JSON.parse(
  searcher.vorkspaceSearch("hello HELLO", "(hello)", "$1!", false, false, true),
);
if (search.matches.length !== 2 || search.matches[0].insert !== "hello!")
  throw new Error("Search smoke check failed");
verifySearch(searcher);
const formatSource = await readFile(formatAsset, "utf8");
const createFormatter = () => {
  const loaded = [];
  const formatter = vm.createContext({
    vorkspaceLoadFormatPlugin(name) {
      const source = formatSources.get(name);
      if (source === undefined)
        throw new Error(`Unknown formatter plugin ${name}`);
      loaded.push(name);
      vm.runInContext(source, formatter);
      return formatter.vorkspaceFormatPlugin;
    },
  });
  vm.runInContext(formatSource, formatter);
  return { formatter, loaded };
};
await verifyFormat(createFormatter, formatPlugins);
await verifyPhp(options, here, sandbox);
const notices = [
  await readFile(
    path.join(here, "node_modules/prettier/THIRD-PARTY-NOTICES.md"),
    "utf8",
  ),
];
for (const scope of ["@codemirror", "@lezer", "@replit"]) {
  for (const name of (
    await readdir(path.join(here, "node_modules", scope))
  ).sort()) {
    const folder = path.join(here, "node_modules", scope, name);
    const pkg = JSON.parse(
      await readFile(path.join(folder, "package.json"), "utf8"),
    );
    notices.push(
      `${pkg.name} ${pkg.version}\n${await readFile(path.join(folder, "LICENSE"), "utf8")}`,
    );
  }
}
for (const name of ["crelt", "style-mod", "w3c-keyname", "prettier"]) {
  const folder = path.join(here, "node_modules", name);
  const pkg = JSON.parse(
    await readFile(path.join(folder, "package.json"), "utf8"),
  );
  notices.push(
    `${pkg.name} ${pkg.version}\n${await readFile(path.join(folder, "LICENSE"), "utf8")}`,
  );
}
await writeFile(asset.replace(/\.js$/, ".LICENSE.txt"), notices.join("\n\n"));
console.log(
  `Built ${path.relative(root, asset)} (${(await readFile(asset)).length} bytes)`,
);
